// kustomize_images は、イメージの名前と digest のファイルの組から、
// Kustomize の images を書いた Component を出力する。
//
//	kustomize_images -out kustomization.yaml api=path/to/api.digest worker=path/to/worker.digest
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"
)

var digestRE = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)

// image は Component の images の1項目。
type image struct {
	name   string
	digest string
}

// readImages は NAME=FILE の引数を読み、FILE に書かれた digest を検査する。
func readImages(args []string) ([]image, error) {
	var images []image
	for _, arg := range args {
		name, path, ok := strings.Cut(arg, "=")
		if !ok || name == "" || path == "" {
			return nil, fmt.Errorf("argument %q is not NAME=FILE", arg)
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		digest := strings.TrimSpace(string(b))
		if !digestRE.MatchString(digest) {
			return nil, fmt.Errorf("%s: %q is not a sha256 digest", path, digest)
		}
		images = append(images, image{name: name, digest: digest})
	}
	sort.Slice(images, func(i, j int) bool { return images[i].name < images[j].name })
	return images, nil
}

// render は Component の YAML を返す。
func render(images []image) string {
	var b strings.Builder
	b.WriteString("# Code generated by //tools/build/kustomize_images. DO NOT EDIT.\n")
	b.WriteString("apiVersion: kustomize.config.k8s.io/v1alpha1\n")
	b.WriteString("kind: Component\n")
	b.WriteString("images:\n")
	for _, img := range images {
		fmt.Fprintf(&b, "  - name: %s\n    digest: %s\n", img.name, img.digest)
	}
	return b.String()
}

func main() {
	out := flag.String("out", "", "output file")
	flag.Parse()
	if *out == "" {
		log.Fatal("-out is required")
	}
	images, err := readImages(flag.Args())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, []byte(render(images)), 0o644); err != nil {
		log.Fatal(err)
	}
}
